package pangea.model.battle

/** Бочки с порохом на поле боя — аура места, а не чья-то: их никто не держит, и
  * сторон они не разбирают. Сколько бочек стоит на поле, лежит на самом бою
  * (`SoloPveBattle.kegs`); ставит их сюжет (просека Чернолома, глава 8).
  *
  * В конце раунда одна из бочек может рвануть: взрыв бьёт мимо брони и
  * поджигает наугад нескольких из тех, кто стоит на поле, — героя, отряд и
  * мобов вперемешку. Рванула последняя — поле стихло. */
object PowderKeg {

  /** Шанс, что в конце раунда рванёт одна из бочек, в %. */
  val ChancePct: Long = 40L

  /** Скольких на поле задевает один взрыв — наугад, своих и чужих. */
  val Victims: Int = 3

  /** Какую долю макс. HP снимает взрыв — мимо брони, как аура. С минибосса —
    * вдвое меньше (см. `BossPercentDamage`). */
  val DamagePct: Long = 10L

  /** Сколько снимет взрыв с того, у кого столько максимума HP. */
  def damageOn(maxHp: Long): Long = (maxHp * DamagePct / 100L).max(1L)
}
