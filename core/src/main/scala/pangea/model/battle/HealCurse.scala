package pangea.model.battle

/** Проклятие Некроманта — след его «Удара проклятой энергией» (см.
  * `MiniBoss.Necromancer`): пока оно держится, раны того, по кому пришёлся
  * удар, — героя или союзника — не затягиваются. HP не восстанавливают ни
  * фляги, ни умения, ни отвары, ни реген, ни кража жизни, ни миазмы. Фляга или
  * умение при этом тратятся и делают всё прочее — кровь, например, снимают, —
  * только HP не прибавляют. Спасения от гибели («Первопроходец», «Каменный
  * страж») и Великанье зелье — не лечение, им проклятие не мешает.
  *
  * Держит остаток раунда, в котором легло, и весь следующий: ставится на
  * [[Turns]] и снимается по одному в самом конце раунда — как паутина (см.
  * [[SpiderWeb]]). С героя его снимает фляга очищения. */
object HealCurse {

  /** На сколько концов раунда проклятие ложится. */
  val Turns: Int = 2

  /** Значок проклятия у HP — героя и союзника. */
  val Icon: String = "🖤"
}
