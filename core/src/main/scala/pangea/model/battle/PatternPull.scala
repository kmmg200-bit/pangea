package pangea.model.battle

/** «Тянет узор» — приём Сборщика на Рубеже II (см. StoryFeedQuest): он сам
  * отмеченный и умеет тянуть чужое Клеймо, как печь в Загоне. Кто тянет, лежит
  * на самом бою (`SoloPveBattle.puller` — его имя); ставит его сюжет.
  *
  * Раз в [[EveryRounds]] раундов, в конце раунда, пока он жив, Сборщик тянет
  * узор из героя — только из героя: Клеймо есть только у него (так решил
  * пользователь). Атака героя падает на [[AttackCutPct]]% на [[Turns]] раунда,
  * а сам Сборщик восстанавливает [[HealPct]]% своего максимума HP. Лежит герой
  * — тянуть не из кого: отряд дерётся с ним как с обычным мобом. Фляга
  * очищения снимает и это. */
object PatternPull {

  /** Раз во столько раундов Сборщик тянет узор. */
  val EveryRounds: Int = 3

  /** На столько процентов падает атака героя, пока узор тянут. */
  val AttackCutPct: Long = 25L

  /** Сколько раундов держится: ставится в конце раунда, тикает в начале хода
    * мобов — герой бьёт ослабленным два раунда подряд. */
  val Turns: Int = 2

  /** Какую долю своего максимума HP Сборщик восстанавливает за раз. */
  val HealPct: Long = 10L

  /** Значок у HP героя, пока узор тянут. */
  val Icon: String = "🩸"

  /** Тянет ли в конце этого раунда: раунды считаются с первого. */
  def due(roundsFought: Int): Boolean = roundsFought > 0 && roundsFought % EveryRounds == 0

  /** Сколько восстановит тот, у кого столько максимума HP. */
  def healOn(maxHp: Long): Long = (maxHp * HealPct / 100L).max(1L)

  /** Атака героя, пока узор тянут. */
  def drainedAtk(atk: Long): Long = atk * (100L - AttackCutPct) / 100L
}
