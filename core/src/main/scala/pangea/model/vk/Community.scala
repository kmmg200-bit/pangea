package pangea.model.vk

/** От имени какого сообщества ВК бот слушает и пишет. Основное — игра в личке,
  * общая и торговая беседы; гильдейское — беседы гильдий и прочие общие беседы:
  * там работают те же команды, что в общей и торговой. Номера бесед у
  * сообществ свои и совпадают (у каждого первая — 2000000001), поэтому беседа —
  * это всегда номер вместе с сообществом. */
sealed trait Community

object Community {
  case object Main   extends Community
  case object Guilds extends Community
}
