  /** Сколько процентов урона по расе даёт каждый висящий трофей. */
  val PctPerTrophy: Int = 1

  private val raceByName: Map[String, Race] =
    Monster.legendaryNames.toList.flatMap { case (race, names) => names.map(_ -> race) }.toMap

  /** Раса именного моба по его имени; None — такого именного нет. */
  def raceOf(monster: String): Option[Race] = raceByName.get(monster)

  /** Прибавка к урону по расам от висящих трофеев: entryName расы → проценты.
    * Повторы не в счёт — каждый именной идёт один раз. */
  def pctByRace(wall: List[String]): Map[String, Int] =
    wall.distinct.flatMap(raceOf).groupBy(_.entryName).view.mapValues(_.size * PctPerTrophy).toMap

  /** Трофей моба `monster` расы `race` (entryName) — если это именной моб и
    * раса его. Уровень — уровень, на котором его взяли. */
  def item(monster: String, race: String, lvl: Long): Option[Item] =
    for {
      title <- titles.get(monster)
      owner <- raceOf(monster) if owner.entryName == race
    } yield Item(
      id = -1L,
      name = title,
      lvl = lvl.max(1L),
      rarity = ItemRarity.Gray,
      itemType = ItemType.NamedTrophy,
      attack = 0,
      accuracy = 0,
      energy = 0,
      armor = 0,
      defence = 0,
      evasion = 0,
      details = ItemDetails.NamedTrophy(monster, owner.entryName)
    )
}
