/** Вид материала-ингредиента (для куба Азата и будущих систем крафта). Не
 *  надевается, лежит в инвентаре как предмет ([[ItemType.Material]] +
 *  [[ItemDetails.Material]]). */
sealed abstract class MaterialKind(val displayName: String) extends EnumEntry {
  /** Описание для инвентаря; по умолчанию его нет. */
  val description: String = ""

  /** Сколько дублонов даёт за материал Ришелье. 0 — обычная продажа за серебро. */
  val doubloonPrice: Long = 0L

  /** Твёрдая цена в серебре у Ришелье — без уровня и редкости (награбленное
    * с обозов). 0 — серебром по общей формуле. */
  val silverPrice: Long = 0L

  /** Пока ни во что не идёт: на карточке под описанием — пометка
    * [[MaterialKind.NotYetUsedNote]]. Войдёт в ремесло — снять (так просил
    * пользователь). */
  val notYetUsed: Boolean = false

  /** Из какого камня получена эта пыль. Задан только у пылей: по нему собирают
    * камень обратно (три пыли — надколотый) и берут грань, которой пыль
    * покрывает оружие. У прочих материалов — None. */
  val gem: Option[GemKind] = None

  /** Ранг травы (1 — простая, 2 — редкая); 0 — не трава. «Странный» и
    * «Необычный» цветки — травы без ранга: герой не понял, что сорвал. */
  val herbRank: Int = 0

  /** Множитель цены травы у Густаво. */
  val herbModifier: Int = 0

  /** Трава: собирается на поляне, сдаётся Густаво, Ришелье её не берёт. */
  def isHerb: Boolean = this == MaterialKind.StrangeFlower || this == MaterialKind.UnusualFlower || herbRank > 0

  /** Добыча, за которую не платят: Ришелье такое не берёт, и серебра за него
   *  не выручить. Место в сумке оно занимает как всё прочее — носят его ради
   *  будущего крафта, а не понадобилось, так выбрасывают. Руками в шкаф такое
   *  положить можно: что держать при себе, решает хозяин. */
  val worthless: Boolean = false
}

